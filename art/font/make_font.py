G = {}


def glyph(ch, rows):
    rows = [r for r in rows.strip("\n").split("\n")]
    assert len(rows) <= 8, (ch, len(rows))
    rows = [r.ljust(8, ".")[:8] for r in rows] + ["........"] * (8 - len(rows))
    G[ch] = rows


