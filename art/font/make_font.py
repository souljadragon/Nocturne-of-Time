order = [chr(c) for c in range(32, 128)]
order[127 - 32] = " "  # DEL
order += [ch for ch, _ in SYMBOLS]
atlas = Image.new("RGBA", (128, 64), (0, 0, 0, 0))
px = atlas.load()
for i, ch in enumerate(order):
    rows = G.get(ch)
    if rows is None:
        rows = G["?"]
    cx, cy = (i % 16) * 8, (i // 16) * 8
    for y, row in enumerate(rows):
        for x, v in enumerate(row):
            if v == "#":
                px[cx + x, cy + y] = (255, 255, 255, 255)

os.makedirs(os.path.dirname(HEADER), exist_ok=True)
data = atlas.tobytes()
lines = ["#pragma once", "", "// Generated by art/font/make_font.py (Nocturne of Time's own 8x8 pixel font). Do not edit.",
         "// 128x64 RGBA32 atlas: 16 x 8 cells of 8x8, ASCII 32-127 then the symbols listed in make_font.py.", "",
         "#include <cstdint>", "", "constexpr int kRetroFontAtlasW = 128;", "constexpr int kRetroFontAtlasH = 64;", "",
         f"alignas(8) static const uint8_t gRetroFontAtlas[{len(data)}] = {{"]
for j in range(0, len(data), 32):
    lines.append("    " + ",".join(f"0x{b:02X}" for b in data[j:j + 32]) + ",")
lines += ["};", ""]
open(HEADER, "w").write("\n".join(lines))

# preview: atlas at 4x, and a sample line
prev = Image.new("RGB", (128 * 4, 64 * 4), (0, 0, 0))
prev.paste(atlas.resize((512, 256), Image.NEAREST), (0, 0), atlas.resize((512, 256), Image.NEAREST))
prev.save(os.path.join(HERE, "font_atlas_preview.png"))
