# Nocturne of Time: write the 32px moon icons as an RGBA32 C header for the game (raw N64 texture data).
#   python3 export_textures.py
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "soh", "soh", "Enhancements", "NocturneOfTime", "Moon", "MoonTextures.h")
ORDER = ["new", "2of8", "3of8", "half", "5of8", "6of8", "7of8", "full"]
SIZE = 32

lines = ["#pragma once", "", "// Generated by art/moon/export_textures.py from the hand-drawn moon icons. Do not edit.",
         "// One 32x32 RGBA32 texture per phase, New Moon to Full Moon.", "", "#include <cstdint>", "",
         f"constexpr int kMoonTexSize = {SIZE};", ""]
names = []
for name in ORDER:
    img = Image.open(os.path.join(HERE, f"moon_{name}_{SIZE}.png")).convert("RGBA")
    assert img.size == (SIZE, SIZE), img.size
    data = img.tobytes()
    var = f"gNocturneMoon_{name}"
    names.append(var)
    lines.append(f"alignas(8) static const uint8_t {var}[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append("")
lines.append("static const uint8_t* const kMoonTextures[8] = { " + ", ".join(names) + " };")
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", OUT)
