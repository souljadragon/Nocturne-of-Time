# Nocturne of Time: the moon dial HUD (icon + phase + "MOON" on a rounded panel), one per phase.
#   python3 make_dial.py
# Writes dial PNGs (2x, for crisp scaling) to art/moon/dial/ and the game's RGBA32 texture header
# soh/soh/Enhancements/NocturneOfTime/Moon/MoonDialTextures.h. Text uses Inter Bold (SIL OFL).
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "dial")
HEADER = os.path.join(HERE, "..", "..", "soh", "soh", "Enhancements", "NocturneOfTime", "Moon", "MoonDialTextures.h")
FONT = "/usr/share/fonts/opentype/inter/Inter-Bold.otf"

ORDER = ["new", "2of8", "3of8", "half", "5of8", "6of8", "7of8", "full"]
LABELS = ["NEW", "2/8", "3/8", "HALF", "5/8", "6/8", "7/8", "FULL"]
W, H = 176, 56  # 2x of the in-game 88x28
SS = 4          # supersampling for smooth edges

BG = (12, 13, 22, 236)
BORDER = (104, 116, 146, 255)
BORDER_FULL = (150, 105, 255, 255)
TEXT = (245, 245, 250, 255)
SUB = (140, 152, 184, 255)


def dial(name, label):
    big = Image.new("RGBA", (W * SS, H * SS), (0, 0, 0, 0))
    d = ImageDraw.Draw(big)
    border = BORDER_FULL if name == "full" else BORDER
    r = 11 * SS
    d.rounded_rectangle([SS, SS, W * SS - SS - 1, H * SS - SS - 1], radius=r, fill=BG, outline=border, width=2 * SS)

    # moon icon on the left
    icon = Image.open(os.path.join(HERE, f"moon_{name}_48.png")).convert("RGBA").resize((46 * SS, 46 * SS),
                                                                                       Image.LANCZOS)
    big.alpha_composite(icon, (6 * SS, (H * SS - 46 * SS) // 2))

    # phase in big type, "MOON" smaller beside it, sharing a baseline
    f_big = ImageFont.truetype(FONT, 25 * SS)
    f_sub = ImageFont.truetype(FONT, 11 * SS)
    x = 60 * SS
    baseline = 37 * SS
    asc_big = f_big.getmetrics()[0]
    d.text((x, baseline - asc_big), label, font=f_big, fill=TEXT)
    x += int(d.textlength(label, font=f_big)) + 6 * SS
    sub = "MOON"
    asc_sub = f_sub.getmetrics()[0]
    for ch in sub:  # letter-spaced
        d.text((x, baseline - asc_sub), ch, font=f_sub, fill=SUB)
        x += int(d.textlength(ch, font=f_sub)) + int(1.2 * SS)
    assert x < (W - 4) * SS, f"{label} doesn't fit"
    return big.resize((W, H), Image.LANCZOS)


os.makedirs(OUT_DIR, exist_ok=True)
lines = ["#pragma once", "",
         "// Generated by art/moon/make_dial.py (moon icons + Inter Bold, SIL OFL). Do not edit.",
         f"// One {W}x{H} RGBA32 dial per phase, New Moon to Full Moon; drawn at half size.", "",
         "#include <cstdint>", "", f"constexpr int kMoonDialW = {W};", f"constexpr int kMoonDialH = {H};", ""]
names = []
sheet = Image.new("RGBA", (W, H * len(ORDER)), (40, 60, 40, 255))
for i, (name, label) in enumerate(zip(ORDER, LABELS)):
    img = dial(name, label)
    img.save(os.path.join(OUT_DIR, f"dial_{name}.png"))
    sheet.alpha_composite(img, (0, i * H))
    data = img.tobytes()
    var = f"gNocturneMoonDial_{name}"
    names.append(var)
    lines.append(f"alignas(8) static const uint8_t {var}[{len(data)}] = {{")
    for j in range(0, len(data), 32):
        lines.append("    " + ",".join(f"0x{b:02X}" for b in data[j:j + 32]) + ",")
    lines.append("};")
    lines.append("")
lines.append("static const uint8_t* const kMoonDials[8] = { " + ", ".join(names) + " };")
open(HEADER, "w").write("\n".join(lines) + "\n")
sheet.save(os.path.join(OUT_DIR, "dial_preview.png"))
print("ok")
